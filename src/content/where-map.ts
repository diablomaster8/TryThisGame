export const WHERE_MAP: Readonly<Record<string, QuestArea>> = Object.fromEntries(
  ROWS.map(([where, region, poi]) => [where, poi === undefined ? { region } : { region, poi }]),
);

/** The area a quest sits in: its own `trigger.area`, else the table row for its `where`. */
export function areaOf(quest: Quest): QuestArea | undefined {
  return quest.trigger.area ?? WHERE_MAP[quest.trigger.where];
}
