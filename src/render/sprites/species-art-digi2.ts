/**
 * Art recipes for the digital line's Versions 2 to 5 (sim/species-digi2.ts), read by both
 * renderers like the rest of species-art.ts. Likeness comes from colour, silhouette and a
 * few signature pieces (a pelt and horn, a mane, sunglasses, a single eye); the four-legged
 * and fish plans and the extras come from creature-kit-digi.ts.
 */
const pal = (
  body: number,
  shade: number,
  belly: number,
  accent: number,
  accent2: number,
  eye: number = C.ink,
  outline: number = C.darkPlum,
): CreaturePalette => ({ body, shade, belly, accent, accent2, eye, outline });

const base: Omit<CreatureSpec, 'colors'> = {
  plan: 'biped',
  size: 1,
  ears: 'none',
  tail: 'none',
  crest: 'none',
  wings: 'none',
  arms: 'stub',
  legs: 'stub',
  eyes: 'dot',
  marks: [],
};

const spec = (colors: CreaturePalette, over: Partial<CreatureSpec>): CreatureSpec => ({
  ...base,
  colors,
  ...over,
});

/** A hatchling: a round blob without limbs. */
const blobby = (colors: CreaturePalette, over: Partial<CreatureSpec>): CreatureSpec =>
  spec(colors, { plan: 'round', size: 0.78, legs: 'none', arms: 'none', eyes: 'big', ...over });

