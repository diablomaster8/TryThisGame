/**
 * R0702: stroke guides for English tracing (letters A-Z, a-z and the digits 0-9) on the same
 * 0-100 board as the kana and Hebrew guides (x right, y down). Plain school print in a
 * standard stroke order: stems first, then bowls, crosses and dots last. Capitals and
 * digits fill y 14-86; lowercase sits on a baseline at y 72 with a body from y 38, tall
 * letters reaching y 10 and tails y 94. Guides for a finger, not font outlines; the glyph
 * itself shows underneath.
 */
import type { ScreenPt as Pt } from './trace-check';

const P = (...xy: number[]): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i + 1 < xy.length; i += 2) out.push({ x: xy[i]!, y: xy[i + 1]! });
  return out;
};

