/**
 * R0699: writes docs/edu-clips-to-record.md, the list a voice actor records for the Learning
 * Grove's fixed lines. Run: npx tsx tests/tools/edu-clip-list.ts
 */
import { writeFileSync } from 'node:fs';
import { EDU_CLIP_IDS, EDU_UI_TEXT, uiClipFile } from '../../src/config/edu-clips';

const group = (id: string): string => id.split('-')[0]!;
const rows: string[] = [];
let last = '';
for (const id of EDU_CLIP_IDS) {
  const g = group(id);
  if (g !== last) {
    rows.push('', `### ${g}`, '', '| File | Say |', '| --- | --- |');
    last = g;
  }
  rows.push(`| \`public/${uiClipFile(id)}\` | ${EDU_UI_TEXT[id]!.replaceAll('|', '/')} |`);
}
const doc = `# Learning Grove clips to record

Generated by \`tests/tools/edu-clip-list.ts\` from \`src/config/edu-clips.ts\`. Nothing here is
recorded yet, and no recording is faked.

${EDU_CLIP_IDS.length} short clips, one warm voice, one take each, no background noise. Save as
mono MP3 (about 64 kbit/s) under the file name shown. Say the words in the right column
exactly; a fragment ("Tap the", "one.") is said alone, with the falling or rising tone it would
have in the middle of the sentence it joins ("Tap the" + "red" + "one.").

When a file lands, add its id to \`EDU_UI_RECORDED\` in \`src/platform/edu-audio.ts\`. A line plays
from recordings only when every clip it needs is listed; otherwise the device voice says it.
The original names ("Nubbin", "Hazel", "Ori") are in the story clips, which are separate (VO
export, \`tests/tools/vo-export.ts\`).
${rows.join('\n')}
`;
writeFileSync('docs/edu-clips-to-record.md', doc);
console.log(`${EDU_CLIP_IDS.length} clips listed`);
