/**
 * R0491 (TECH-50): regenerate src/sim/side-story-skeleton.ts from the side-story scripts.
 * Run `npx tsx tests/tools/gen-side-skeleton.ts` after any change to a side story, fun quest
 * or expansion; tests/sim/side-skeleton.test.ts fails while the committed file is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildSideSkeleton } from './side-skeleton-build';

const out = fileURLToPath(new URL('../../src/sim/side-story-skeleton.ts', import.meta.url));
const json = JSON.stringify(await buildSideSkeleton());
// A single-quoted literal (Prettier's choice for JSON, which is full of double quotes).
const literal = `'${json.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const src = `/**
 * GENERATED by tests/tools/gen-side-skeleton.ts from the side-story scripts: do not edit.
 * R0491 (TECH-50): what the sim needs of every side story before its text chunk loads
 * (see side-story-files.ts). JSON.parse keeps the boot parse cheap.
 */
import type { SideSkeleton } from './side-story-files';

export const SIDE_STORY_SKELETON: SideSkeleton = JSON.parse(
  ${literal},
) as SideSkeleton;
`;
writeFileSync(out, src);
console.log(`wrote ${out}: ${(json.length / 1024).toFixed(0)} kB JSON`);
